async function createDocx() {
  const children: Paragraph[] = [
    new Paragraph({
      children: [
        new TextRun({
          text: '【JFT-Basic A2】第7課 会話・表現 練習問題（25問）',
          bold: true,
          size: 28,
        }),
      ],
    }),
    new Paragraph({ text: '' }),
    new Paragraph({
      children: [
        new TextRun({
          text: '（　　）に入れるのに最もよいものを、ひとつ選んでください。',
          size: 22,
        }),
      ],
    }),
    new Paragraph({ text: '' }),
  ];

  kaiwaData.forEach((item) => {
    children.push(
      new Paragraph({
        children: [
          new TextRun({
            text: `${item.num}.\n${item.q}`,
            size: 24,
          }),
        ],
      })
    );
    item.options.forEach((opt) => {
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: opt,
              size: 24,
            }),
          ],
        })
      );
    });
    children.push(new Paragraph({ text: '' }));
  });

  const doc = new Document({
    sections: [{ properties: {}, children }],
  });

  const buffer = await Packer.toBuffer(doc);
  const outPath = path.resolve('..', 'Bank Soal JFT-Basic A2/Bab 07/Latihan_JFT_A2_Bab7_KaiwaHyougen.docx');
  fs.writeFileSync(outPath, buffer);
  console.log('✅ Berhasil membuat:', outPath);
}

createDocx();
